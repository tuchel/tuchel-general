import assert from 'node:assert/strict';
import * as T from 'three';
import {build} from 'esbuild';
await build({entryPoints:['lib/house-model/atmosphere.ts','lib/house-model/experience.ts'],outdir:'tmp/motion-check',outExtension:{'.js':'.mjs'},bundle:true,platform:'node',format:'esm',packages:'external'});
const {atmosphere}=await import('../tmp/motion-check/atmosphere.mjs');
// Leaves and grass share one material here, as the detailed model's cards and blades can.
const root=new T.Group(),material=new T.MeshStandardMaterial(),depth=new T.MeshDepthMaterial();
const leaves=new T.InstancedMesh(new T.PlaneGeometry(),material,2);leaves.userData.sway='leaf';leaves.customDepthMaterial=depth;
const grass=new T.InstancedMesh(new T.PlaneGeometry(),material,2);grass.name='meadow-grass';root.add(leaves,grass);
const air=atmosphere(root);
assert.equal(air.breezing,false,'breeze starts off; the scene is still until asked');
const compile=(m,lib)=>{const s={uniforms:{},vertexShader:T.ShaderLib[lib].vertexShader,fragmentShader:T.ShaderLib[lib].fragmentShader,defines:{}};m.onBeforeCompile(s,null);return s;};
const standard=compile(material,'physical'),shadow=compile(depth,'depth');
assert.equal(standard.vertexShader.split('uniform float uBreezeTime').length-1,1,'one breeze per shared material');
assert(shadow.vertexShader.includes('breezeAmount'),'shadows sway with the leaves');
air.breeze(true);assert.equal(air.breezing,true);air.breeze(false);
let preferenceChanged,state;const preference={matches:false,addEventListener:(_,fn)=>preferenceChanged=fn,removeEventListener:()=>{}};
globalThis.window={matchMedia:()=>preference};
const {createCaptures}=await import('../tmp/motion-check/experience.mjs');
const captures=createCaptures({scene:new T.Scene(),camera:new T.PerspectiveCamera(),renderer:{domElement:{}},root:new T.Group(),lighting:{},invalidate(){},onState:s=>state=s,heavy:false,eyeLevel:()=>false,orbit(){},beginOrbit:()=>true});
captures.breeze(true);assert.equal(state.breeze,true);
preference.matches=true;preferenceChanged();assert.equal(state.breeze,false,'reduced motion turns the breeze off');
await captures.photograph();assert.match(state.message,/computer/,'phones keep the live view instead of path tracing');
assert.equal(captures.tick(1000),false,'no tracer, the viewer keeps the canvas');
captures.dispose();
console.log('Passed: breeze off by default and once per material, shadows sway with leaves, reduced motion observed, heavy captures limited to computers.');
