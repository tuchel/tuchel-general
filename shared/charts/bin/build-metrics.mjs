// Advance widths and kerning pairs from the chart faces' .woff2 files, as one
// module per face that the kit can use in Node and in the browser alike. The
// check render and the live figure then measure text identically.
//
// Run: npm run metrics   (writes src/fonts/<id>.generated.ts for every face below)
//
// To add an app's face: put its .woff2 files and a .css with matching
// @font-face rules in fonts/, add an entry here, and run the script.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';

const HERE = dirname(fileURLToPath(import.meta.url));
const FONTS = join(HERE, '..', 'fonts');

const FACES = [
  {
    id: 'inter',
    name: 'INTER',
    family: 'Inter',
    stack: 'Inter, system-ui, sans-serif',
    files: { 400: 'Inter-400.woff2', 500: 'Inter-500.woff2', 600: 'Inter-600.woff2', 700: 'Inter-700.woff2' },
  },
];

const EXTRA = '’‘“”–—…×÷−·•→←↑↓≈≤≥±µ∝°€£¥§¶©®™½¼¾²³¹′″∼√∞∆ΔαβγδεθλμπσφωΩ';
const chars = [];
for (let cp = 0x20; cp <= 0x7e; cp++) chars.push(String.fromCodePoint(cp));
for (let cp = 0xa0; cp <= 0xff; cp++) chars.push(String.fromCodePoint(cp));
for (const ch of EXTRA) chars.push(ch);
const KERN_SET = chars.filter((ch) => ch.codePointAt(0) < 0x7f || '’‘“”–—'.includes(ch));

for (const face of FACES) {
  const weights = {};
  for (const [weight, file] of Object.entries(face.files)) {
    const f = fontkit.openSync(join(FONTS, file));
    const upm = f.unitsPerEm;
    const adv = {};
    let sum = 0;
    let n = 0;
    for (const ch of chars) {
      const g = f.glyphForCodePoint(ch.codePointAt(0));
      if (!g || g.id === 0) continue;
      adv[ch] = g.advanceWidth;
      if (/[a-z]/.test(ch)) { sum += g.advanceWidth; n++; }
    }
    const kern = {};
    for (const a of KERN_SET) {
      if (!(a in adv)) continue;
      for (const b of KERN_SET) {
        if (!(b in adv)) continue;
        const k = f.layout(a + b).advanceWidth - adv[a] - adv[b];
        if (Math.abs(k) >= 8) kern[a + b] = k;
      }
    }
    weights[weight] = { upm, fallback: Math.round(sum / n), adv, kern };
    console.log(`${face.family} ${weight}: ${Object.keys(adv).length} glyphs, ${Object.keys(kern).length} kern pairs`);
  }
  const body = `// Generated by bin/build-metrics.mjs from fonts/${Object.values(face.files).join(', ')}. Do not edit.
import type { Face } from './types.ts';

export const ${face.name}: Face = ${JSON.stringify({ family: face.family, stack: face.stack, weights })};
`;
  const out = join(HERE, '..', 'src', 'fonts', `${face.id}.generated.ts`);
  writeFileSync(out, body);
  console.log(`wrote src/fonts/${face.id}.generated.ts (${(body.length / 1024).toFixed(0)} KB)`);
}
