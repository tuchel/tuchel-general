// One ESM file with the D3 modules the kit uses, so apps (which install
// only their own dependencies) and Node scripts resolve nothing from npm.
//
// Run: npm run vendor   (writes vendor/d3.js)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const entry = `
export { scaleLinear, scaleLog, scaleBand, scalePoint, scaleSqrt, scaleTime } from 'd3-scale';
export { line, area, curveLinear, curveMonotoneX, curveStep, arc, pie } from 'd3-shape';
export { interpolate, interpolateNumber, interpolateArray, interpolateObject, interpolateRgb, interpolateString } from 'd3-interpolate';
export { format, formatPrefix } from 'd3-format';
export { extent, max, min, sum, range, ticks, tickStep, bisector, group, rollup } from 'd3-array';
`;
const result = await build({
  stdin: { contents: entry, resolveDir: join(HERE, '..'), loader: 'js' },
  bundle: true,
  format: 'esm',
  minify: true,
  legalComments: 'none',
  write: false,
});
const banner = `// D3 subset for the chart kit, generated by bin/build-vendor.mjs.
// d3-array 3.2.4, d3-format 3.1.0, d3-interpolate 3.0.1, d3-scale 4.0.2, d3-shape 3.2.0, and their
// dependencies. Copyright 2010-2023 Mike Bostock. ISC License: https://github.com/d3/d3/blob/main/LICENSE
`;
writeFileSync(join(HERE, '..', 'vendor', 'd3.js'), banner + result.outputFiles[0].text);
writeFileSync(join(HERE, '..', 'vendor', 'd3.d.ts'), `export * from 'd3-scale';\nexport * from 'd3-shape';\nexport * from 'd3-interpolate';\nexport * from 'd3-format';\nexport * from 'd3-array';\n`);
console.log(`wrote vendor/d3.js (${(result.outputFiles[0].text.length / 1024).toFixed(1)} KB)`);
